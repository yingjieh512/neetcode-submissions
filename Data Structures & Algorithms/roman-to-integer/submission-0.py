
class Solution:
    def romanToInt(self, s: str) -> int:
        # 第一步：建立字典，存储每个罗马数字对应的整数
        roman = {
            "I": 1,
            "V": 5,
            "X": 10,
            "L": 50,
            "C": 100,
            "D": 500,
            "M": 1000
        }

        # res 用来记录最终的整数结果
        res = 0

        # 第二步：从左往右遍历字符串
        for i in range(len(s)):

            # 如果当前位置不是最后一个字符，
            # 并且当前罗马数字的值小于右边的罗马数字
            #
            # 就说明当前数字需要被减去
            #
            # 例如：
            # IV = 4
            # I = 1，V = 5
            # 因为 1 < 5，所以先减去 1
            # 下一轮再加上 5，得到 -1 + 5 = 4
            #
            # XL = 40
            # X = 10，L = 50
            # 因为 10 < 50，所以减去 10
            #
            # i < len(s) - 1 是为了防止访问 s[i+1] 越界
            if i < len(s) - 1 and roman[s[i]] < roman[s[i + 1]]:
                res -= roman[s[i]]

            # 如果当前数字大于或等于右边的数字，
            # 或者已经到达最后一个字符，
            # 就正常加上当前数字
            #
            # 例如：
            # VI = 6
            # V = 5，I = 1
            # 5 > 1，所以加上 5
            # 最后再加上 1，得到 6
            else:
                res += roman[s[i]]

        # 第三步：返回最终结果
        return res
