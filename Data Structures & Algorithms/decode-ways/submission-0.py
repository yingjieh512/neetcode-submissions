class Solution:
    def numDecodings(self, s: str) -> int:
        n = len(s)

        # dp[i] 表示前 i 个字符有多少种合法的解码方式
        dp = [0] * (n + 1)

        # 空字符串有 1 种解码方式，作为 DP 的初始状态
        dp[0] = 1

        # 从第一个字符开始，逐步计算前 i 个字符的答案
        for i in range(1, n + 1):

            # 情况 1：把最后一个数字单独解码
            # s[i-1] 是前 i 个字符中的最后一个数字
            # 只有 1-9 可以单独解码，0 不可以
            if s[i - 1] != "0":
                dp[i] += dp[i - 1]

            # 情况 2：把最后两个数字一起解码
            # 必须至少有两个字符
            # 并且最后两个数字必须在 10 到 26 之间
            if i >= 2 and 10 <= int(s[i - 2:i]) <= 26:
                dp[i] += dp[i - 2]

        # 返回整个字符串的解码方式数量
        return dp[n]